"""Export the verified discrete model for firmware gain validation."""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def export_protocol_model():
    d=json.loads((ROOT/'shared/design.json').read_text())
    digest=hashlib.sha256((ROOT/'shared/robot.json').read_bytes()).hexdigest()
    if d['config_sha256']!=digest or d['state_order']!=['theta_rad','omega_rad_s']:
        raise ValueError('Design/config mismatch')
    lines=['// Generated by tools/generate_lqr_protocol.py. Do not edit.','#pragma once','namespace lqr_model {',f'constexpr const char* hash="{digest}";']
    for i in range(2):
        for j in range(2):lines.append(f'constexpr double a{i}{j}={d["Ad"][i][j]:.17g};')
        lines.append(f'constexpr double b{i}={d["Bd"][i][0]:.17g};')
    lines.append('}')
    (ROOT/'03_Firmware_ESP32S3/balancebot/GeneratedLqrModel.h').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':export_protocol_model()
