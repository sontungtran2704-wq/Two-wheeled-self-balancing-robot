"""Independent numerical design and nonlinear plant; SI throughout."""
from pathlib import Path
import json, hashlib, math, csv
import numpy as np
from scipy.linalg import expm, solve_discrete_are

ROOT=Path(__file__).resolve().parents[1]
def load_config(): return json.loads((ROOT/'shared/robot.json').read_text(encoding='utf-8'))
def coefficients(p):
    m,r,l=p['mb'],p['r'],p['l']
    # Rectangular locked-rotor surrogate, subtract spin inertia before adding it to M.
    Jc=m*p['h']**2/12-2*p['Ir']
    Jc*=p.get('Jc_scale',1)
    M=m+2*p['mw']+2*(0.5*p['mw']*r*r+p['Ir'])/(r*r)
    J=Jc+m*l*l
    return M,J,J+2*r*m*l+r*r*M,m*l+r*M
def dynamics(s,u,p,push=0):
    th,w,q,x=s; m,r,l,g=p['mb'],p['r'],p['l'],p['g']
    M,J,_,_=coefficients(p); b=m*l*math.cos(th)+r*M
    H=J+2*r*m*l*math.cos(th)+r*r*M
    wd=(m*g*l*math.sin(th)-b*u+r*m*l*math.sin(th)*w*w+push)/H
    return np.array([w,wd,u,q+r*w])
def torque(s,u,p,push=0):
    th,w,_,_=s; M,_,_,_=coefficients(p); r=p['r']; ml=p['mb']*p['l']
    wd=dynamics(s,u,p,push)[1]
    return r*(M*(u+r*wd)+ml*math.cos(th)*wd-ml*math.sin(th)*w*w)
def rk4(s,u,p,dt,push=0):
    f=lambda z:dynamics(z,u,p,push)
    k1=f(s);k2=f(s+dt*k1/2);k3=f(s+dt*k2/2);k4=f(s+dt*k3)
    return s+dt*(k1+2*k2+2*k3+k4)/6
def design_lqr(c,baseline=False):
    p=c['model']; _,_,H,b=coefficients(p)
    A=np.array([[0,1],[p['mb']*p['g']*p['l']/H,0]])
    B=np.array([[0],[-b/H]])
    e=expm(np.block([[A,B],[np.zeros((1,3))]])*c['timing']['lqr_s'])
    Ad,Bd=e[:2,:2],e[:2,2:]
    Q=np.diag(c['lqr']['baseline_Q' if baseline else 'Q']); R=c['lqr']['baseline_R' if baseline else 'R']
    P=solve_discrete_are(Ad,Bd,Q,[[R]])
    K=np.linalg.solve([[R]]+Bd.T@P@Bd,Bd.T@P@Ad)
    return A,B,Ad,Bd,K,P
def export():
    c=load_config(); A,B,Ad,Bd,K,P=design_lqr(c)
    cfg_hash=hashlib.sha256((ROOT/'shared/robot.json').read_bytes()).hexdigest()
    o=dict(config_id=c['config_id'],config_sha256=cfg_hash,schema_version=1,physical_status='UNVERIFIED',state_order=c['lqr']['state_order'],input=c['lqr']['input'],Ts=c['timing']['lqr_s'],Q=c['lqr']['Q'],R=c['lqr']['R'],A=A.tolist(),B=B.tolist(),C=np.eye(2).tolist(),D=[[0],[0]],Ad=Ad.tolist(),Bd=Bd.tolist(),K=K[0].tolist(),P=P.tolist(),poles=[[z.real,z.imag] for z in np.linalg.eigvals(Ad-Bd@K)],baseline_K=design_lqr(c,True)[4][0].tolist(),model=c['model'],pid=c['pid'],drive=c['drive'])
    (ROOT/'shared/design.json').write_text(json.dumps(o,indent=2),encoding='utf-8')
    _,_,H,b=coefficients(c['model'])
    # Single generated header used in target and host builds.
    lines=['// Generated by tools/design.py. Do not edit.','#pragma once','namespace cfg {',f'constexpr const char* id="{c["config_id"]}";',f'constexpr const char* sha256="{cfg_hash}";']
    constants=dict(dt=c['timing']['lqr_s'],pid_dt=c['timing']['pid_s'],k0=K[0,0],k1=K[0,1],r=c['model']['r'],track=c['model']['W'],g=c['model']['g'],mb=c['model']['mb'],l=c['model']['l'],M=coefficients(c['model'])[0],lean_gain=b/(c['model']['mb']*c['model']['g']*c['model']['l']),vmax=c['drive']['max_relative_speed'],amax=c['drive']['max_relative_accel'],steps_per_m=c['drive']['full_steps']*c['drive']['microstep']/(2*math.pi*c['model']['r']))
    constants.update({k:v for k,v in c['pid'].items() if isinstance(v,(int,float))})
    constants.update(c['safety'])
    for group in ('velocity','yaw'):
        constants.update({f'{group}_{k}':v for k,v in c['pid'][group].items()})
    for k,v in constants.items(): lines.append(f'constexpr double {k}={v:.17g};')
    lines+=['constexpr unsigned lease_us=400000, imu_max_age_us=15000, stable_us=1000000;','}']
    dest=ROOT/'03_Firmware_ESP32S3/balancebot/GeneratedConfig.h';dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    from generate_lqr_protocol import export_protocol_model
    export_protocol_model()
    print(json.dumps(dict(K=o['K'],poles=o['poles'],A=o['A'],B=o['B'],sha256=cfg_hash)))
if __name__=='__main__': export()
